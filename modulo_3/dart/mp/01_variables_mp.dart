// Ejercicio: declarar variables de un servidor usando var, final y const
void main() {
  var nombreServidor = 'srv-01';
  final ipServidor = '192.168.1.10';
  const puertoDefault = 8080;

  print('Servidor: $nombreServidor');
  print('IP: $ipServidor');
  print('Puerto por defecto: $puertoDefault');
}
